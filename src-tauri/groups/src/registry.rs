use std::{collections::BTreeMap, collections::HashMap, fs, io, path::Path};
use tauri::{ipc::Invoke, Wry};

pub struct Arg {
  pub name: &'static str,
  pub ty: String,
  pub optional: bool,
}
pub struct Sig {
  pub args: Vec<Arg>,
  pub ret: String,
}

/// One `#[command]`. Submitted by the macro
pub struct CommandEntry {
  pub group: &'static str,
  pub name: &'static str,
  pub wire: &'static str,
  pub sig: fn() -> Sig,
  pub call: fn(Invoke<Wry>) -> bool,
}
/// One `#[derive(TsType)]`.
pub struct TypeEntry {
  pub name: &'static str,
  pub decl: fn() -> String,
}
inventory::collect!(CommandEntry);
inventory::collect!(TypeEntry);

fn commands() -> Vec<&'static CommandEntry> {
  let mut v: Vec<_> = inventory::iter::<CommandEntry>().collect();
  v.sort_by_key(|c| (c.group, c.name));
  for w in v.windows(2) {
    if w[0].wire == w[1].wire {
      panic!(
        "command `{}.{}` is defined twice; names must be unique within a group",
        w[0].group, w[0].name
      );
    }
  }
  v
}

/// `Builder::default().invoke_handler(tauri_groups::handler())`
///
/// Pinned to `Wry` because `tauri::AppHandle` (no type arg) means `AppHandle<Wry>`.
pub fn handler() -> impl Fn(Invoke<Wry>) -> bool + Send + Sync + 'static {
  let map: HashMap<&'static str, &'static CommandEntry> =
    commands().into_iter().map(|c| (c.wire, c)).collect();
  move |invoke| match map.get(invoke.message.command()).copied() {
    Some(c) => (c.call)(invoke),
    None => false,
  }
}

/// The whole frontend file as a string.
pub fn render_ts() -> String {
  let mut types: Vec<&TypeEntry> = inventory::iter::<TypeEntry>().collect();
  types.sort_by_key(|t| t.name);
  for w in types.windows(2) {
    if w[0].name == w[1].name {
      panic!(
        "two `#[derive(TsType)]` types are both named `{}`",
        w[0].name
      );
    }
  }

  let mut s = String::from(
    "// WARN: AUTO-GENERATED by tauri-groups. Do not edit.\n\
         import { invoke } from \"@tauri-apps/api/core\";\n\n",
  );
  for t in types {
    s += &(t.decl)();
    s += "\n\n";
  }

  let mut groups: BTreeMap<&str, Vec<&CommandEntry>> = BTreeMap::new();
  for c in commands() {
    groups.entry(c.group).or_default().push(c);
  }
  s += "export const commands = {\n";
  for (g, list) in groups {
    s += &format!("  {g}: {{\n");
    for c in list {
      let sig = (c.sig)();
      let name = camel(c.name);
      if sig.args.is_empty() {
        s += &format!("    {name}: () => invoke<{}>(\"{}\"),\n", sig.ret, c.wire);
      } else {
        let fields: Vec<_> = sig
          .args
          .iter()
          .map(|a| format!("{}{}: {}", a.name, if a.optional { "?" } else { "" }, a.ty))
          .collect();
        // all-optional args -> the whole object is optional too
        let q = if sig.args.iter().all(|a| a.optional) {
          "?"
        } else {
          ""
        };
        s += &format!(
          "    {name}: (args{q}: {{ {} }}) => invoke<{}>(\"{}\", args),\n",
          fields.join("; "),
          sig.ret,
          c.wire
        );
      }
    }
    s += "  },\n";
  }
  s += "} as const;\n";
  s
}

/// Write the frontend file (only touches it if the content changed, so no HMR spam).
pub fn export_ts(path: impl AsRef<Path>) -> io::Result<()> {
  let path = path.as_ref();
  let s = render_ts();
  if fs::read_to_string(path).ok().as_deref() == Some(&s) {
    return Ok(());
  }
  if let Some(dir) = path.parent() {
    fs::create_dir_all(dir)?;
  }
  fs::write(path, s)
}

fn camel(s: &str) -> String {
  let (mut out, mut up) = (String::new(), false);
  for c in s.chars() {
    if c == '_' {
      up = true;
    } else if up {
      out.extend(c.to_uppercase());
      up = false;
    } else {
      out.push(c);
    }
  }
  out
}
